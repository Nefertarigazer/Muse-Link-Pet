#!/usr/bin/env python3
"""publish-release.py - deterministic release pipeline (no LLM in the loop).

Executes one publish-release bridge request end to end (retired type names,
muselink_id.RETIRED_TYPES, are accepted for requests queued before a rename):

  1 validate fields          version x.y.z, 64-hex hashes, sizes, .zip
  2 version guard            strictly newer than the live manifest
  3 approval gate            RELEASE_APPROVAL = popup | delay:<minutes> | none
  4 PC-side verification     file-facts.ps1 measures the declared files
  5 chunked upload           PC -> server through the scheduled task
                             bridge-publish-upload (no trigger; /run only)
  6 assemble + hash check    on the server, against the DECLARED hashes
  7 move into place          + flip latest.json (backup kept) unless test mode
  8 public verification      manifest and downloads; any failure rolls back

What changed on 2026-11-12 (review findings P0-2, P0-4):
  * no request field is ever spliced into a PowerShell command line: paths go
    to the PC inside JSON argument files read by fixed scripts;
  * the hash chain only proves "bytes == what the requester declared", not
    who the requester is, so a mechanism gate (approval) exists and is ON by
    default; RELEASE_ALLOWED_DIRS can pin where packages may come from;
  * the Setup executable ships only when its hash is declared (setup_sha256);
  * the upload task has no trigger (the old "/sc once /st 23:59" re-ran every
    upload that night) and the pipeline fails fast on the uploader's FATAL;
  * replies carry facts only - no instructions to the requester.

Identity protocol v3 (implemented 2026-11-12) (docs/protocol.en.md sections 3-4):
  * Stage 3 becomes muselink_id.flows.authorize() when the identity module
    is installed (MUSELINK_IDENTITY=1). ctx: auth from RE-VERIFYING
    envelopes/<req_id>.json (envelope.verify_request, check_freshness=False;
    a v1 request -> "legacy_unsigned"); action "publish-release"; grant_id
    from the verified inner request; facts measured in stage 4:
      version          the validated x.y.z string
      package_path     file-facts full_path, or None if reparse_in_path
      package_sha256   measured hash (equals the declared one by now)
      package_size     measured size (int)
      setup_present    bool
      test             bool (payload test is True)
  * Stage 3 must stay AFTER stage 4 (facts first) and BEFORE stage 5 (the
    first side effect). proceed False -> Refuse("approval", how) and reply
    needs-user, exactly like a declined card today. The final reply names
    the grant used and its uses left.
  * The old approval_gate() / RELEASE_APPROVAL path is kept only while
    MUSELINK_IDENTITY is not 1; delete it after legacy_unsigned = reject.

Config: KEY=VALUE lines in $MUSELINK_PUBLISH_CONFIG or
~/.config/muselink/publish.env (generated by vm/install.sh from the site file;
template config/muselink.site.example.json, section "publish").
Usage: publish-release.py <request.json> [--no-reply]
Exit 0 = published (or test-mode verified); non-zero = refused/failed. A JSON
verdict is the last stdout line.
"""
