def load_publish_config():
    path = os.environ.get("MUSELINK_PUBLISH_CONFIG") or os.path.join(HOME, ".config/muselink/publish.env")
    cfg = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
                v = v[1:-1]
            cfg[k.strip()] = os.path.expanduser(v)
    return cfg


CFG = load_publish_config()


