def log(msg):
    line = f"{time.strftime('%Y-%m-%dT%H:%M:%S%z')} {msg}"
    print(line, flush=True)
    try:
        with open(f"{BRIDGE}/pipeline.log", "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception:
        pass


def run(cmd, timeout=120, input_text=None, env=None):
    p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace",
                       timeout=timeout, input=input_text, env=env)
    return p.returncode, (p.stdout or ""), (p.stderr or "")


def server(cmd, timeout=120):
    return run(SERVER_SSH + [SERVER, cmd], timeout=timeout)


def psq(s):
    return "'" + str(s).replace("'", "''") + "'"


def pc_ps(code, timeout=120):
    return run([PC_SH, "ps", code], timeout=timeout)


def pc_put_json(obj, name):
    """Upload a JSON args file into the PC tool dir; return its Windows path."""
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", suffix=".json", delete=False) as f:
        json.dump(obj, f, ensure_ascii=False)
        local = f.name
    try:
        fwd = PC_TOOL_DIR.replace("\\", "/") + "/" + name
        rc, out, err = run([PC_SH, "scp-to", local, fwd], timeout=120)
        if rc != 0:
            raise Refuse("pc_io", f"could not stage {name} on the PC: {(err or out).strip()[:200]}")
    finally:
        os.unlink(local)
    return PC_TOOL_DIR + "\\" + name


def semver(v):
    return tuple(int(x) for x in v.split("."))


class Refuse(Exception):
    def __init__(self, stage, detail):
        super().__init__(detail)
        self.stage, self.detail = stage, detail


def pc_file_facts(paths, tries=3):
    """{path: {exists,size,sha256}} measured on the PC by file-facts.ps1."""
    args_path = pc_put_json({"paths": paths}, "publish-facts-args.json")
    code = f"& {psq(PC_TOOL_DIR + chr(92) + 'file-facts.ps1')} -ArgsFile {psq(args_path)}"
    err = ""
    for attempt in range(tries):
        rc, out, err = pc_ps(code, timeout=300)
        for line in reversed(out.strip().splitlines()):
            try:
                d = json.loads(line)
            except Exception:
                continue
            if d.get("ok"):
                files = d.get("files") or []
                if isinstance(files, dict):
                    files = [files]
                return {f["path"]: f for f in files}
            err = d.get("error", "")
            break
        time.sleep(10)
    raise Refuse("pc_verify", f"cannot measure files on the PC ({(err or 'no output')[:200]})")


def ensure_upload_task():
    launcher = PC_TOOL_DIR + "\\launcher.exe"
    arg = '"' + PC_TOOL_DIR + '\\chunked-upload.ps1" -ArgsFile "' + PC_TOOL_DIR + '\\upload-args.json"'
    code = f"""
$name = 'bridge-publish-upload'
$a = New-ScheduledTaskAction -Execute {psq(launcher)} -Argument {psq(arg)} -WorkingDirectory {psq(PC_TOOL_DIR)}
# a task without triggers reads back Triggers = $null, and @($null).Count is 1
function Get-TriggerCount($task) {{ @($task.Triggers | Where-Object {{ $null -ne $_ }}).Count }}
$t = Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
$needs = (-not $t) -or ((Get-TriggerCount $t) -gt 0) -or ($t.State -eq 'Disabled') -or ($t.Actions[0].Arguments -ne $a.Arguments)
if ($needs) {{
  $p = New-ScheduledTaskPrincipal -UserId ($env:USERDOMAIN + '\\' + $env:USERNAME) -LogonType Interactive -RunLevel Limited
  $s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew
  $s.ExecutionTimeLimit = 'PT2H'
  Register-ScheduledTask -TaskName $name -Action $a -Principal $p -Settings $s -Force | Out-Null
}}
$t = Get-ScheduledTask -TaskName $name
'TASK_READY triggers=' + (Get-TriggerCount $t) + ' state=' + $t.State
"""
    rc, out, err = pc_ps(code, timeout=120)
    if "TASK_READY triggers=0" not in out:
        raise Refuse("upload", f"upload task not ready: {(out + err).strip()[:300]}")


def pc_upload_status():
    code = (f"$p = {psq(PC_TOOL_DIR + chr(92) + 'upload-work' + chr(92) + 'status.txt')}; "
            "if (Test-Path -LiteralPath $p) { Get-Content -LiteralPath $p -Tail 2 } else { 'NO_STATUS' }")
    rc, out, _ = pc_ps(code, timeout=60)
    return out


def approval_gate(req, version, files, pkg_path):
    mode = APPROVAL.strip().lower()
    if mode == "none":
        return "none"
    who = str(req.get("from", "?"))[:40]
    sizes = ", ".join(f"{n} {s / 1048576:.1f} MB" for n, s, _ in files)
    if mode == "popup":
        rendered = labels("release.approval.opt.")
        rendered["release.approval.opt.approve"] = APPROVE_LABEL or rendered["release.approval.opt.approve"]
        rendered["release.approval.opt.decline"] = DECLINE_LABEL or rendered["release.approval.opt.decline"]
        if len(set(rendered.values())) != len(rendered):
            raise Refuse("approval", "approval labels must be distinct")
        text = t("release.approval.body", version=version, agent=who, files=sizes, path=pkg_path, hash=files[0][2][:16])
        env = dict(os.environ, POPUP_WAIT_MAX=str(APPROVAL_TIMEOUT))
        rc, out, err = run([POPUP_ASK, text, rendered["release.approval.opt.approve"], rendered["release.approval.opt.decline"]], timeout=APPROVAL_TIMEOUT + 120, env=env)
        if "REFUSED" in (out + err):
            raise Refuse("approval", "another card is waiting for the user; release postponed (send again later)")
        m = re.search(r"---RESULT---\n(.*)", out, re.S)
        answer = (m.group(1).strip() if m else "")
        if re.search(r"^KIND:pet_done\s*$", out, re.M) or answer_key(answer, rendered) != "release.approval.opt.approve":
            raise Refuse("approval", f"not approved by the user (answer: {answer or 'none'})")
        return "popup"
    if mode.startswith("delay:"):
        minutes = int(mode.split(":", 1)[1])
        cancel = f"{BRIDGE}/cancel/{req['req_id']}"
        os.makedirs(os.path.dirname(cancel), exist_ok=True)
        run([POPUP_ASK, "--no-wait", t("release.delay.body", minutes=minutes, version=version, agent=who)], timeout=180)
        deadline = time.time() + minutes * 60
        while time.time() < deadline:
            if os.path.exists(cancel):
                raise Refuse("approval", "cancelled by the user during the delay window")
            time.sleep(10)
        return f"delay:{minutes}"
    raise Refuse("approval", f"unknown RELEASE_APPROVAL mode {APPROVAL!r}")


def identity_authorize(req, req_id, version, files, pkg_path, z, setup_present, test_mode):
    """Re-verify the stored envelope and run flows.authorize() (identity v3)."""
    try:
        if VM_DIR not in sys.path:
            sys.path.insert(0, VM_DIR)
        from muselink_id import flows, inbound
        from muselink_id.store import Store
        from muselink_id.policy import Policy
        from muselink_id.registry import Registry
        from muselink_id.grants import Grants
        from muselink_id.ui import PopupUI, PcAdapter
        store = Store().open()
        policy_path = os.environ.get("MUSELINK_POLICY") or os.path.join(HOME, ".config/muselink/policy.json")
        policy = Policy.from_file(policy_path)
        registry = Registry(store)
        grants = Grants(store, policy, registry)
        # Same rules as `muselink-id authorize`: re-verify the stored
        # envelope; a request that claims to be verified but has no valid
        # envelope is refused instead of being treated as legacy.
        auth, agent, agent_id, inner, legacy_from = inbound.reverify(
            store, registry, policy, req_id, time.time(), worker=req)
        grant_id = inner.get("grant_id") if inner else None
        if auth.startswith("failed"):
            raise Refuse("approval", f"identity check failed: {auth.split(':', 1)[-1]}")
        facts = {
            "version": version,
            "package_path": z.get("full_path") if not z.get("reparse_in_path") else None,
            "package_sha256": z.get("sha256"),
            "package_size": z.get("size"),
            "setup_present": bool(setup_present),
            "test": bool(test_mode),
        }
        ctx = {"auth": auth, "agent": agent, "agent_id": agent_id, "req_id": req_id,
               "action": "publish-release", "facts": facts, "grant_id": grant_id,
               "legacy_from": legacy_from}
        out = flows.authorize(ctx, policy=policy, grants=grants, ui=PopupUI(VM_DIR),
                              store=store, now_fn=time.time)
        if not out.proceed:
            raise Refuse("approval", f"identity denied: {out.how} ({out.reason})")
        uses_left = None
        if out.grant_id:
            for g in grants.public_list(int(time.time())):
                if g.get("grant_id") == out.grant_id:
                    uses_left = g.get("uses_left")
        return out.how, out.grant_id, uses_left
    except Refuse:
        raise
    except Exception as e:
        raise Refuse("approval", f"identity authorization failed: {e}")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    no_reply = "--no-reply" in sys.argv
    if not args:
        print("usage: publish-release.py <request.json> [--no-reply]")
        return 2
    with open(args[0], encoding="utf-8") as f:
        req = json.load(f)
    req_id = str(req.get("req_id", ""))
    payload = req.get("payload") or {}
    test_mode = bool(payload.get("test"))
    version = str(payload.get("version", ""))
    declared_sha = str(payload.get("sha256", "")).lower()
    declared_size = payload.get("package_size")
    pkg_path = str(payload.get("package_path", ""))
    setup_path = str(payload.get("setup_path", "") or "")
    setup_sha = str(payload.get("setup_sha256", "") or "").lower()
    setup_size = payload.get("setup_size")
    notes = str(payload.get("notes", ""))[:500]

    def reply(status, text):
        if no_reply or not VALID_ID.match(req_id):
            log(f"reply suppressed ({status}) for {req_id!r}")
            return
        fd, tf = tempfile.mkstemp(suffix=".txt")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        try:
            run([REPLY, req_id, status, tf], timeout=120)
        finally:
            os.unlink(tf)

    def alert(text):
        try:
            os.makedirs(f"{BRIDGE}/alerts", exist_ok=True)
            with open(f"{BRIDGE}/alerts/{req_id or 'unknown'}.txt", "w", encoding="utf-8") as f:
                f.write(text)
        except Exception:
            pass

    old_v = None
    flipped = [False]
    used_grant = None
    uses_left = None

    def rollback_manifest():
        if flipped[0] and old_v:
            server(f"sudo mv {WEB_DIR}/latest.json.bak-{old_v} {WEB_DIR}/latest.json "
                   f"&& sudo chmod 644 {WEB_DIR}/latest.json", timeout=60)
            flipped[0] = False

    try:
        # ---- 1 validate
        if not VALID_ID.match(req_id):
            raise Refuse("validate", "bad req_id")
        if current_type(req.get("type")) not in PUBLISH_TYPES:
            raise Refuse("validate", f"not a release request: {req.get('type')}")
        if not VERSION_RX.match(version):
            raise Refuse("validate", f"bad version: {version!r}")
        if not HEX64.match(declared_sha):
            raise Refuse("validate", "sha256 is not 64 hex chars")
        if not isinstance(declared_size, int) or declared_size <= 0:
            raise Refuse("validate", f"bad package_size: {declared_size!r}")
        if not pkg_path.lower().endswith(".zip"):
            raise Refuse("validate", "package_path is not a .zip")
        if ALLOWED_DIRS and not any(pkg_path.lower().startswith(d.lower().rstrip("\\") + "\\") for d in ALLOWED_DIRS):
            raise Refuse("validate", "package_path is outside RELEASE_ALLOWED_DIRS")
        if setup_path and (not HEX64.match(setup_sha) or not isinstance(setup_size, int) or setup_size <= 0):
            raise Refuse("validate", "setup_path declared without a valid setup_sha256 / setup_size")
        zip_name = ZIP_NAME.format(version=version)
        setup_name = SETUP_NAME.format(version=version) if SETUP_NAME else ""
        for n in filter(None, (zip_name, setup_name)):
            if not SAFE_NAME.match(n):
                raise Refuse("validate", f"unsafe published name {n!r}")
        if setup_path and not setup_name:
            raise Refuse("validate", "a setup file was declared but RELEASE_SETUP_NAME is not configured")
        log(f"{req_id}: stage1 ok version={version} test={test_mode}")

        # ---- 2 version guard
        with urllib.request.urlopen(LATEST_URL, timeout=30) as r:
            online = json.load(r)
        old_v = str(online.get("version", "0.0.0"))
        if not VERSION_RX.match(old_v):
            old_v = "0.0.0"
        if semver(version) <= semver(old_v):
            raise Refuse("version_guard", f"requested {version} is not newer than online {old_v}")
        log(f"{req_id}: stage2 ok online={old_v}")

        # ---- 4 PC-side measurement (before asking the user: show real facts)
        paths = [pkg_path] + ([setup_path] if setup_path else [])
        facts = pc_file_facts(paths)
        z = facts.get(pkg_path) or {}
        if not z.get("exists"):
            raise Refuse("pc_verify", f"declared package not found on the PC: {pkg_path}")
        if z.get("sha256") != declared_sha or z.get("size") != declared_size:
            raise Refuse("pc_verify", f"hash chain broken at source: declared sha={declared_sha} "
                                      f"size={declared_size}; measured sha={z.get('sha256')} size={z.get('size')}")
        files = [(zip_name, declared_size, declared_sha, pkg_path)]
        if setup_path:
            s = facts.get(setup_path) or {}
            if not s.get("exists") or s.get("sha256") != setup_sha or s.get("size") != setup_size:
                raise Refuse("pc_verify", f"declared setup does not match on the PC: measured "
                                          f"sha={s.get('sha256')} size={s.get('size')}")
            files.append((setup_name, setup_size, setup_sha, setup_path))
        log(f"{req_id}: stage4 ok {len(files)} file(s) match the declaration")

        # ---- 3 approval gate
        if os.environ.get("MUSELINK_IDENTITY") == "1":
            gate, used_grant, uses_left = identity_authorize(
                req, req_id, version, files, pkg_path, z, bool(setup_path), test_mode)
            log(f"{req_id}: stage3 identity gate={gate} grant={used_grant or '-'}")
        else:
            gate = approval_gate(req, version, [(n, sz, h) for n, sz, h, _ in files], pkg_path)
            log(f"{req_id}: stage3 gate={gate}")

        # ---- 5 upload (PC -> server stage), judged by bytes on the server
        pc_put_json({"files": [{"path": p, "size": sz, "remote_name": n} for n, sz, _, p in files],
                     "dest": UPLOAD_DEST, "key": UPLOAD_KEY, "remote_dir": STAGE,
                     "chunks": 16, "parallel": 16}, "upload-args.json")
        ensure_upload_task()
        # a status.txt left by an earlier run must not be read as this run's
        pc_ps(f"Remove-Item -LiteralPath {psq(PC_TOOL_DIR + chr(92) + 'upload-work' + chr(92) + 'status.txt')} "
              "-Force -ErrorAction SilentlyContinue", timeout=60)
        rc, out, err = run([PC_SH, "ssh", "schtasks /Run /TN bridge-publish-upload"], timeout=60)
        if rc != 0:
            raise Refuse("upload", f"could not start the upload task: {(out + err).strip()[:200]}")
        names = " ".join(n for n, _, _, _ in files)
        deadline = time.time() + UPLOAD_WAIT_SECS
        landed = {}
        while time.time() < deadline:
            time.sleep(20)
            status = pc_upload_status()
            if "FATAL" in status:
                raise Refuse("upload", f"PC uploader failed: {status.strip()[-300:]}")
            rc, out, _ = server(
                f"cd ~/{STAGE} 2>/dev/null && for f in {names}; do "
                f"stat -c%s $f.part* 2>/dev/null | awk -v n=$f '{{s+=$1}} END {{print n, s+0}}'; done",
                timeout=60)
            landed = {}
            for line in (out or "").splitlines():
                parts = line.rsplit(" ", 1)
                if len(parts) == 2 and parts[1].isdigit():
                    landed[parts[0]] = int(parts[1])
            if all(landed.get(n) == s for n, s, _, _ in files) and "ALLDONE" in status:
                break
        if not all(landed.get(n) == s for n, s, _, _ in files):
            raise Refuse("upload", f"staged parts {landed} != expected after {UPLOAD_WAIT_SECS}s")
        log(f"{req_id}: stage5 ok all parts landed")

        # ---- 6 assemble + whole-file hash against the DECLARED hashes
        asm = " && ".join([f"cd ~/{STAGE}"] + [f"cat {n}.part* > {n}" for n, _, _, _ in files]
                          + ["sha256sum " + names])
        rc, out, err = server(asm, timeout=300)
        landed_hash = {os.path.basename(fn): h for h, fn in re.findall(r"([0-9a-f]{64})\s+(\S+)", out or "")}
        for n, _, h, _ in files:
            if landed_hash.get(n) != h:
                raise Refuse("assemble", f"{n} landed hash {landed_hash.get(n)} != declared {h}")
        log(f"{req_id}: stage6 ok landed hashes match the declaration")

        # ---- 7 move into place (+ manifest flip unless test mode)
        target = TEST_DIR if test_mode else WEB_DIR
        server(f"sudo mkdir -p {target}", timeout=60)
        rc, out, err = server(" && ".join(f"sudo mv ~/{STAGE}/{n} {target}/{n} && sudo chmod 644 {target}/{n}"
                                          for n, _, _, _ in files), timeout=120)
        if rc != 0:
            raise Refuse("publish", f"move into {target} failed: {err[:200]}")
        server("rm -f " + " ".join(f"~/{STAGE}/{n}.part*" for n, _, _, _ in files), timeout=60)
        if test_mode:
            log(f"{req_id}: stage7 TEST MODE - files in {TEST_DIR}, manifest untouched")
            reply("ok", f"TEST release {version} verified end to end; files in the test dir, manifest untouched.")
            print(json.dumps({"ok": True, "test": True, "version": version}))
            return 0
        manifest = {"version": version, "publishedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "url": f"{BASE_URL}/{zip_name}", "sha256": declared_sha, "size": declared_size,
                    "notes": notes}
        if setup_path:
            manifest["setup"] = {"url": f"{BASE_URL}/{setup_name}", "sha256": setup_sha, "size": setup_size}
        rc, out, err = run(SERVER_SSH + [SERVER, "cat > /tmp/muselink-latest-new.json"], timeout=120,
                           input_text=json.dumps(manifest, ensure_ascii=False, indent=2))
        if rc != 0:
            raise Refuse("publish", f"manifest upload failed: {err[:200]}")
        # The server's web user must be able to read the manifest (a 0660
        # manifest once made latest.json 403 while the zips stayed 200).
        rc, out, err = server(f"sudo cp {WEB_DIR}/latest.json {WEB_DIR}/latest.json.bak-{old_v} "
                              f"&& sudo mv /tmp/muselink-latest-new.json {WEB_DIR}/latest.json "
                              f"&& sudo chmod 644 {WEB_DIR}/latest.json", timeout=60)
        if rc != 0:
            raise Refuse("publish", f"latest.json flip failed: {err[:200]}")
        flipped[0] = True
        log(f"{req_id}: stage7 ok manifest flipped to {version}")

        # ---- 8 public verification; any failure rolls the manifest back
        def rollback():
            rollback_manifest()

        verified, last_err = False, None
        for attempt in range(3):
            try:
                with urllib.request.urlopen(LATEST_URL, timeout=30) as r:
                    live = json.load(r)
                if live.get("version") != version or live.get("sha256") != declared_sha:
                    rollback()
                    raise Refuse("public_verify", f"live manifest shows {live.get('version')}; rolled back to {old_v}")
                for n, s, _, _ in files:
                    rq = urllib.request.Request(f"{BASE_URL}/{n}", method="HEAD")
                    with urllib.request.urlopen(rq, timeout=30) as r:
                        if r.status != 200 or int(r.headers.get("Content-Length", 0)) != s:
                            rollback()
                            raise Refuse("public_verify", f"HEAD {n}: {r.status} len={r.headers.get('Content-Length')} "
                                                          f"!= {s}; rolled back to {old_v}")
                verified = True
                break
            except Refuse:
                raise
            except Exception as e:
                last_err = e
                log(f"{req_id}: stage8 attempt {attempt + 1} failed: {e}")
                time.sleep(15)
        if not verified:
            rollback()
            raise Refuse("public_verify", f"public verification unreachable after 3 attempts ({last_err}); "
                                          f"manifest rolled back to {old_v}")
        log(f"{req_id}: stage8 ok public verification passed")
        lines = [f"release {version} published (gate: {gate}).",
                 f"zip sha256={declared_sha} size={declared_size}: declared = measured on the PC = landed on the server."]
        if setup_path:
            lines.append(f"setup sha256={setup_sha} size={setup_size} (same three-way match).")
        if used_grant:
            lines.append(f"grant {used_grant} used; uses left: {uses_left}.")
        lines.append(f"latest.json now {version} (previous kept as latest.json.bak-{old_v}); public manifest and downloads verified.")
        reply("ok", "\n".join(lines))
        print(json.dumps({"ok": True, "version": version, "zip_sha256": declared_sha, "setup": bool(setup_path)}))
        return 0

    except Refuse as e:
        try:
            rollback_manifest()
        except Exception:
            pass
        msg = f"release {version or '?'} REFUSED at {e.stage}: {e.detail}"
        log(f"{req_id}: {msg}")
        status = "needs-user" if e.stage == "approval" else "error"
        reply(status, msg + "\nNothing was published (or the manifest was rolled back).")
        alert(msg)
        print(json.dumps({"ok": False, "stage": e.stage, "detail": e.detail}))
        return 1
    except Exception as e:
        try:
            rollback_manifest()   # never leave a flipped manifest behind an error reply
        except Exception:
            pass
        msg = f"release {version or '?'} FAILED unexpectedly: {e}"
        log(f"{req_id}: {msg}")
        reply("error", msg + "\nNot published, or rolled back if the manifest had flipped.")
        alert(msg)
        print(json.dumps({"ok": False, "stage": "exception", "detail": str(e)[:300]}))
        return 1


if __name__ == "__main__":
    sys.exit(main())
